export const FIRST_CHAR = 32;
export const CHAR_WIDTH = 6;        // 5 pixels of glyph plus one of spacing
export const CHAR_HEIGHT = 8;       // 7 rows of glyph plus one of leading

/**
 * One byte per row, 8 rows per glyph, bit 7 leftmost. Compiled once at load:
 * the bitmaps above are the source of truth, this is what drawing reads.
 */
export const FONT: Uint8Array = (() => {
    const rows = new Uint8Array(GLYPHS.length * CHAR_HEIGHT);
    for (let g = 0; g < GLYPHS.length; ++g) {
        const bitmap = GLYPHS[g].split(" ");
        for (let y = 0; y < bitmap.length; ++y) {
            let bits = 0;
            for (let x = 0; x < 5; ++x) if (bitmap[y][x] === "1") bits |= 0x80 >> x;
            rows[g * CHAR_HEIGHT + y] = bits;
        }
    }
    return rows;
})();

/** Row offset of a character's glyph in FONT, or of "?" when it has none. */
export function glyphOffset(code: number): number {
    const index = code - FIRST_CHAR;
    return (index >= 0 && index < GLYPHS.length ? index : "?".charCodeAt(0) - FIRST_CHAR) * CHAR_HEIGHT;
}
